import { readFileSync, writeFileSync } from "node:fs";

/**
 * Regenerates the base64 asset modules the heatmap renderer imports.
 *
 *   pnpm gen-assets
 *
 * The wasm and TTF are inlined as modules because Vercel's function tracer only
 * ships what it can resolve statically — files read via `fs` at runtime
 * disappear from the deployed bundle (see docs/gotchas.md).
 */

const wrap = (b64: string): string => {
  // One array element per chunk, joined at runtime: a `"a" + "b" + …` chain
  // builds a deep expression tree and V8 blows the parse stack (~27k terms).
  const lines = b64.match(/.{1,120}/g) ?? [];
  return `[\n${lines.map((line) => `  "${line}",`).join("\n")}\n].join("")`;
};

const header = (source: string, license: string): string =>
  `// Generated by scripts/gen-assets.ts from ${source} (${license}).\n` +
  `// Inlined as a module because Vercel's function tracer does not copy files\n` +
  `// read at runtime. Do not edit; re-run \`pnpm gen-assets\`.\n`;

const wasm = readFileSync("assets/resvg.wasm").toString("base64");
writeFileSync(
  "lib/resvg-wasm-base64.ts",
  `${header("assets/resvg.wasm", "@resvg/resvg-wasm, MPL-2.0")}export const RESVG_WASM_BASE64 =\n${wrap(wasm)};\n`,
);

const font = readFileSync("assets/IBMPlexSans-Regular.ttf").toString("base64");
writeFileSync(
  "lib/plex-sans-base64.ts",
  `${header("assets/IBMPlexSans-Regular.ttf", "IBM Plex Sans, SIL OFL 1.1")}export const PLEX_SANS_BASE64 =\n${wrap(font)};\n`,
);

console.log(`resvg.wasm: ${wasm.length} base64 bytes · Plex Sans: ${font.length} base64 bytes`);
